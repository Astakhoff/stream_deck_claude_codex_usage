const { test } = require('node:test');
const assert = require('node:assert/strict');
const { WebSocketServer } = require('ws');
const { spawn } = require('node:child_process');
const { once } = require('node:events');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

test('official SDK transport registers, routes keys, persists mode and targets the active inspector', {timeout:15000}, async (t) => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'weekly-sdk-'));
  const server = new WebSocketServer({host:'127.0.0.1',port:0});
  await once(server,'listening');
  let child;
  t.after(async()=>{ child?.kill(); for(const c of server.clients)c.terminate(); await new Promise(r=>server.close(r)); await fs.rm(temp,{recursive:true,force:true}); });
  const entry = process.env.WEEKLY_SDK_TEST_ENTRY || path.resolve(__dirname,'../bin/marketplace-plugin.mjs');
  const bootstrap = path.join(temp,'bootstrap.mjs');
  await fs.writeFile(bootstrap, `import { createRequire } from 'node:module';\nconst req=createRequire(${JSON.stringify(pathToFileURL(entry).href)});\nfor(const name of ['./desktop','./codex']){req(name);req.cache[req.resolve(name)].exports={fetchUsage:async()=>({remaining:36,resetsAt:'2099-12-01T00:00Z',fetchedAt:Date.now(),resetCredits:{known:true,grants:[]}})}}\nawait import(${JSON.stringify(pathToFileURL(entry).href)});`);
  const connected=once(server,'connection');
  const info={application:{version:'7.4.2',language:'en',platform:'mac',platformVersion:'13',font:'Arial'},plugin:{uuid:'com.astakhoff.claude-codex-weekly-usage',version:'1.7.0.0'},devices:[{id:'device',type:2,name:'Stream Deck XL',size:{columns:8,rows:4}}],devicePixelRatio:1};
  child=spawn(process.execPath,[bootstrap,'-port',String(server.address().port),'-pluginUUID','test-plugin','-registerEvent','registerPlugin','-info',JSON.stringify(info)],{cwd:temp,env:{...process.env,HOME:temp,CODEX_HOME:temp},stdio:['ignore','pipe','pipe']});
  const messages=[];
  const [socket]=await connected;
  socket.on('message',b=>messages.push(JSON.parse(b)));
  const waitFor=async(predicate)=>{for(let i=0;i<300;i++){const result=messages.find(predicate);if(result)return result;await new Promise(r=>setTimeout(r,10));}throw new Error('Expected SDK command not received');};
  await waitFor(m=>m.event==='registerPlugin');
  const emit=(event,context='key',payload={})=>socket.send(JSON.stringify({event,action:'com.astakhoff.claude-codex-weekly-usage.codex-weekly',context,device:'device',payload:{controller:'Keypad',coordinates:{column:0,row:0},settings:{},...payload}}));
  const imageHas=(m,text)=>m.event==='setImage'&&Buffer.from(m.payload.image.split(',')[1],'base64').toString().includes(text);
  emit('willAppear');
  await waitFor(m=>imageHas(m,'>36%</'));
  emit('propertyInspectorDidAppear');
  await waitFor(m=>m.event==='sendToPropertyInspector'&&m.payload.percentMode==='remaining');
  emit('keyDown');
  await waitFor(m=>imageHas(m,'>64%</'));
  const saved=await waitFor(m=>m.event==='setSettings');
  assert.equal(saved.payload.percentMode,'used');
  emit('didReceiveSettings','key',{settings:saved.payload});
  await waitFor(m=>m.event==='sendToPropertyInspector'&&m.payload.percentMode==='used');
  assert.equal(messages.filter(m=>m.event==='registerPlugin').length,1);
});
